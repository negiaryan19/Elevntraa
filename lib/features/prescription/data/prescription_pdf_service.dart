import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../../../core/utils/app_paths.dart';
import '../../../domain/models/doctor_profile.dart';
import '../../../domain/models/medical_insight.dart';
import '../../../domain/models/medication.dart';
import '../../../domain/models/patient.dart';
import '../../../domain/models/visit.dart';

/// Generates an NMC-standard Indian out-patient prescription PDF.
/// White background, teal (#00796B) accent only.
/// All doctor/clinic data pulled from [DoctorProfile]; no hardcoded values.
class PrescriptionPdfService {
  // 1mm ≈ 2.835 PDF points
  static const _mm = 2.835;

  static final _teal = PdfColor.fromInt(0xFF00796B);
  static final _ink = PdfColor.fromInt(0xFF1A1A1A);
  static final _grey = PdfColor.fromInt(0xFF6B7280);
  static final _lightGrey = PdfColor.fromInt(0xFFBDBDBD);
  static final _rowAlt = PdfColor.fromInt(0xFFF5F5F5);

  Future<Uint8List> build({
    required VisitRecord visit,
    required PatientProfile? patient,
    DoctorProfile doctor = DoctorProfile.defaultProfile,
  }) async {
    final theme = await _loadTheme();
    final insight = visit.insight ?? MedicalInsight.empty;
    final instructions =
        insight.instructions.where((s) => s.trim().isNotEmpty).toList();
    final advice =
        insight.advice.where((s) => s.trim().isNotEmpty).toList();
    final hasFollowUp =
        insight.followUpDays != null && insight.followUpDays! > 0;

    final doc = pw.Document(
      title: 'Prescription — ${patient?.name ?? 'Patient'}',
      author: doctor.name,
      creator: 'Rxvarta',
    );

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        theme: theme,
        margin: pw.EdgeInsets.fromLTRB(
          15 * _mm, // left 15mm
          20 * _mm, // top 20mm
          15 * _mm, // right 15mm
          15 * _mm, // bottom 15mm
        ),
        footer: (ctx) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.SizedBox(height: 4),
            pw.Container(height: 1, color: _teal),
            pw.SizedBox(height: 4),
            pw.Text(
              'This is a computer-generated prescription',
              textAlign: pw.TextAlign.center,
              style: pw.TextStyle(fontSize: 8, color: _grey),
            ),
            pw.Text(
              'Generated by RxVarta AI  |  Secure  |  Private',
              textAlign: pw.TextAlign.center,
              style: pw.TextStyle(fontSize: 8, color: _grey),
            ),
          ],
        ),
        build: (ctx) => [
          _doctorHeader(doctor),
          pw.SizedBox(height: 8),
          pw.Container(height: 1, color: _teal),
          pw.SizedBox(height: 12),
          _patientRow(visit, patient),
          pw.SizedBox(height: 16),
          if (insight.diagnosis.trim().isNotEmpty) ...[
            _diagnosisSection(insight.diagnosis),
            pw.SizedBox(height: 14),
          ],
          _medicinesSection(insight.medications),
          if (instructions.isNotEmpty) ...[
            pw.SizedBox(height: 14),
            _instructionsSection(instructions),
          ],
          if (advice.isNotEmpty) ...[
            pw.SizedBox(height: 14),
            _adviceSection(advice),
          ],
          if (hasFollowUp) ...[
            pw.SizedBox(height: 14),
            _followUpSection(visit.createdAt, insight.followUpDays!),
          ],
          pw.SizedBox(height: 28),
          _signatureBlock(visit, doctor),
          pw.SizedBox(height: 14),
        ],
      ),
    );

    await _addAttachmentPages(doc, theme, visit, patient);
    return doc.save();
  }

  Future<void> _addAttachmentPages(
    pw.Document doc,
    pw.ThemeData theme,
    VisitRecord visit,
    PatientProfile? patient,
  ) async {
    final attachments = visit.attachments;
    if (attachments.isEmpty) return;

    for (var i = 0; i < attachments.length; i++) {
      final att = attachments[i];
      Uint8List? bytes;
      try {
        final file = File(AppPaths.resolveAttachment(att.path));
        if (file.existsSync()) bytes = await file.readAsBytes();
      } catch (_) {
        bytes = null;
      }
      if (bytes == null) continue;

      final image = pw.MemoryImage(bytes);
      final caption = att.caption.trim().isEmpty
          ? 'Report ${i + 1}'
          : att.caption.trim();

      doc.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          theme: theme,
          margin: pw.EdgeInsets.fromLTRB(
            15 * _mm,
            20 * _mm,
            15 * _mm,
            15 * _mm,
          ),
          build: (context) => pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.stretch,
            children: [
              if (i == 0) ...[
                pw.Text(
                  'PREVIOUS REPORTS',
                  style: pw.TextStyle(
                    fontSize: 14,
                    fontWeight: pw.FontWeight.bold,
                    color: _teal,
                    letterSpacing: 0.8,
                  ),
                ),
                pw.Text(
                  'Attached for ${patient?.name ?? 'patient'}',
                  style: pw.TextStyle(fontSize: 9, color: _grey),
                ),
                pw.SizedBox(height: 6),
                pw.Divider(color: _lightGrey, thickness: 0.5),
                pw.SizedBox(height: 8),
              ],
              pw.Text(
                '${i + 1}. $caption',
                style: pw.TextStyle(
                  fontSize: 9.5,
                  fontWeight: pw.FontWeight.bold,
                  color: _ink,
                ),
              ),
              pw.SizedBox(height: 6),
              pw.Expanded(
                child: pw.Center(
                  child: pw.Image(image, fit: pw.BoxFit.contain),
                ),
              ),
            ],
          ),
        ),
      );
    }
  }

  String fileName(PatientProfile? patient, VisitRecord visit) {
    final who = (patient?.name ?? 'patient')
        .replaceAll(RegExp(r'[^A-Za-z0-9]+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '');
    final d = visit.createdAt;
    final stamp =
        '${d.year}${d.month.toString().padLeft(2, '0')}${d.day.toString().padLeft(2, '0')}';
    return 'Prescription_${who.isEmpty ? 'patient' : who}_$stamp.pdf';
  }

  Future<void> printOrPreview({
    required VisitRecord visit,
    required PatientProfile? patient,
    DoctorProfile doctor = DoctorProfile.defaultProfile,
  }) async {
    final bytes = await build(visit: visit, patient: patient, doctor: doctor);
    await Printing.layoutPdf(
      onLayout: (_) => bytes,
      name: fileName(patient, visit),
    );
  }

  Future<void> shareAsFile({
    required VisitRecord visit,
    required PatientProfile? patient,
    DoctorProfile doctor = DoctorProfile.defaultProfile,
  }) async {
    final bytes = await build(visit: visit, patient: patient, doctor: doctor);
    await Printing.sharePdf(bytes: bytes, filename: fileName(patient, visit));
  }

  // ── Theme ─────────────────────────────────────────────────────────────────

  Future<pw.ThemeData> _loadTheme() async {
    try {
      final base = await PdfGoogleFonts.notoSansRegular();
      final bold = await PdfGoogleFonts.notoSansBold();
      final italic = await PdfGoogleFonts.notoSansItalic();
      final deva = await PdfGoogleFonts.notoSansDevanagariRegular();
      final devaBold = await PdfGoogleFonts.notoSansDevanagariBold();
      return pw.ThemeData.withFont(
        base: base,
        bold: bold,
        italic: italic,
        fontFallback: [deva, devaBold],
      );
    } catch (_) {
      return pw.ThemeData.base();
    }
  }

  // ── Section 1: Doctor Header ──────────────────────────────────────────────

  pw.Widget _doctorHeader(DoctorProfile d) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        // Doctor credentials — left
        pw.Expanded(
          flex: 3,
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                d.name,
                style: pw.TextStyle(
                  fontSize: 16,
                  fontWeight: pw.FontWeight.bold,
                  color: _ink,
                ),
              ),
              if (d.qualifications.trim().isNotEmpty) ...[
                pw.SizedBox(height: 3),
                pw.Text(
                  d.qualifications,
                  style: pw.TextStyle(fontSize: 11, color: _grey),
                ),
              ],
              if (d.regNo.trim().isNotEmpty) ...[
                pw.SizedBox(height: 2),
                pw.Text(
                  'Reg. No: ${d.regNo}',
                  style: pw.TextStyle(fontSize: 10, color: _grey),
                ),
              ],
            ],
          ),
        ),
        pw.SizedBox(width: 16),
        // Clinic details — right
        pw.Expanded(
          flex: 2,
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              if (d.clinicName.trim().isNotEmpty)
                pw.Text(
                  d.clinicName,
                  textAlign: pw.TextAlign.right,
                  style: pw.TextStyle(
                    fontSize: 11,
                    fontWeight: pw.FontWeight.bold,
                    color: _ink,
                  ),
                ),
              if (d.clinicAddress.trim().isNotEmpty) ...[
                pw.SizedBox(height: 2),
                pw.Text(
                  d.clinicAddress,
                  textAlign: pw.TextAlign.right,
                  style: pw.TextStyle(fontSize: 10, color: _grey),
                ),
              ],
              if (d.clinicPhone.trim().isNotEmpty) ...[
                pw.SizedBox(height: 2),
                pw.Text(
                  'Phone: ${d.clinicPhone}',
                  textAlign: pw.TextAlign.right,
                  style: pw.TextStyle(fontSize: 10, color: _grey),
                ),
              ],
            ],
          ),
        ),
      ],
    );
  }

  // ── Section 2: Patient Details + Date ────────────────────────────────────

  pw.Widget _patientRow(VisitRecord visit, PatientProfile? p) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Row(
          children: [
            pw.Expanded(flex: 6, child: _lv('Patient', p?.name ?? '—')),
            pw.Expanded(
              flex: 4,
              child: _lv('Date', _ddmmyyyy(visit.createdAt)),
            ),
          ],
        ),
        pw.SizedBox(height: 6),
        pw.Row(
          children: [
            pw.Expanded(
              flex: 2,
              child: _lv('Age', p?.age != null ? '${p!.age} yrs' : '—'),
            ),
            pw.Expanded(flex: 2, child: _lv('Gender', _genderLabel(p?.sex))),
            pw.Expanded(flex: 6, child: _lv('Phone', _phoneLabel(p))),
          ],
        ),
      ],
    );
  }

  // ── Section 3: Diagnosis with ℞ symbol ───────────────────────────────────

  pw.Widget _diagnosisSection(String diagnosis) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          '℞', // ℞ PRESCRIPTION TAKE
          style: pw.TextStyle(
            fontSize: 24,
            color: _teal,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 4),
        pw.RichText(
          text: pw.TextSpan(
            children: [
              pw.TextSpan(
                text: 'Diagnosis: ',
                style: pw.TextStyle(
                  fontSize: 12,
                  fontWeight: pw.FontWeight.bold,
                  color: _ink,
                ),
              ),
              pw.TextSpan(
                text: diagnosis,
                style: pw.TextStyle(fontSize: 12, color: _ink),
              ),
            ],
          ),
        ),
      ],
    );
  }

  // ── Section 4: Medicines Table ────────────────────────────────────────────

  pw.Widget _medicinesSection(List<Medication> meds) {
    if (meds.isEmpty) {
      return pw.Text(
        'No medicines prescribed.',
        style: pw.TextStyle(fontSize: 10, color: _grey),
      );
    }
    return _medicinesTable(meds);
  }

  pw.Widget _medicinesTable(List<Medication> meds) {
    final headerStyle = pw.TextStyle(
      fontSize: 10,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.white,
    );
    final cellStyle = pw.TextStyle(fontSize: 10, color: _ink);

    pw.Widget hcell(String text) => pw.Padding(
      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
      child: pw.Text(text, style: headerStyle),
    );

    pw.Widget dcell(String text, {bool bold = false}) => pw.Padding(
      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
      child: pw.Text(
        text.trim().isEmpty ? '' : text,
        style: bold
            ? cellStyle.copyWith(fontWeight: pw.FontWeight.bold)
            : cellStyle,
      ),
    );

    return pw.Table(
      border: pw.TableBorder.all(color: _lightGrey, width: 0.5),
      columnWidths: const {
        0: pw.FlexColumnWidth(0.5), // # ~5%
        1: pw.FlexColumnWidth(2.5), // Medicine ~25%
        2: pw.FlexColumnWidth(1.5), // Dosage ~15%
        3: pw.FlexColumnWidth(2.0), // Frequency ~20%
        4: pw.FlexColumnWidth(1.5), // Duration ~15%
        5: pw.FlexColumnWidth(2.0), // Timing ~20%
      },
      children: [
        pw.TableRow(
          decoration: pw.BoxDecoration(color: _teal),
          children: [
            hcell('#'),
            hcell('Medicine'),
            hcell('Dosage'),
            hcell('Frequency'),
            hcell('Duration'),
            hcell('Timing'),
          ],
        ),
        for (var i = 0; i < meds.length; i++)
          pw.TableRow(
            decoration: pw.BoxDecoration(
              color: i.isEven ? PdfColors.white : _rowAlt,
            ),
            children: [
              dcell('${i + 1}'),
              dcell(meds[i].name.toUpperCase(), bold: true),
              dcell(meds[i].dosage),
              dcell(meds[i].frequency),
              dcell(meds[i].duration),
              dcell(meds[i].timing),
            ],
          ),
      ],
    );
  }

  // ── Section 5: Instructions ───────────────────────────────────────────────

  pw.Widget _instructionsSection(List<String> instructions) {
    return pw.Container(
      decoration: pw.BoxDecoration(
        border: pw.Border(
          left: pw.BorderSide(color: _teal, width: 2),
        ),
      ),
      padding: const pw.EdgeInsets.only(left: 10),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'Instructions:',
            style: pw.TextStyle(
              fontSize: 11,
              fontWeight: pw.FontWeight.bold,
              color: _ink,
            ),
          ),
          pw.SizedBox(height: 4),
          for (final instr in instructions)
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 2),
              child: pw.Text(
                '•  $instr',
                style: pw.TextStyle(fontSize: 10, color: _ink),
              ),
            ),
        ],
      ),
    );
  }

  // ── Section 6: Advice ────────────────────────────────────────────────────

  pw.Widget _adviceSection(List<String> advice) {
    return pw.Container(
      decoration: pw.BoxDecoration(
        border: pw.Border(
          left: pw.BorderSide(color: _teal, width: 2),
        ),
      ),
      padding: const pw.EdgeInsets.only(left: 10),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'Advice:',
            style: pw.TextStyle(
              fontSize: 11,
              fontWeight: pw.FontWeight.bold,
              color: _ink,
            ),
          ),
          pw.SizedBox(height: 4),
          for (final item in advice)
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 2),
              child: pw.Text(
                item,
                style: pw.TextStyle(fontSize: 10, color: _ink),
              ),
            ),
        ],
      ),
    );
  }

  // ── Section 7: Follow-up ─────────────────────────────────────────────────

  pw.Widget _followUpSection(DateTime visitDate, int days) {
    final nextDate = visitDate.add(Duration(days: days));
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.RichText(
          text: pw.TextSpan(
            children: [
              pw.TextSpan(
                text: 'Follow-up: ',
                style: pw.TextStyle(
                  fontSize: 10,
                  fontWeight: pw.FontWeight.bold,
                  color: _ink,
                ),
              ),
              pw.TextSpan(
                text: 'After $days day${days == 1 ? '' : 's'}',
                style: pw.TextStyle(fontSize: 10, color: _ink),
              ),
            ],
          ),
        ),
        pw.SizedBox(height: 2),
        pw.RichText(
          text: pw.TextSpan(
            children: [
              pw.TextSpan(
                text: 'Next visit: ',
                style: pw.TextStyle(
                  fontSize: 10,
                  fontWeight: pw.FontWeight.bold,
                  color: _ink,
                ),
              ),
              pw.TextSpan(
                text: _ddmmyyyy(nextDate),
                style: pw.TextStyle(fontSize: 10, color: _ink),
              ),
            ],
          ),
        ),
      ],
    );
  }

  // ── Section 8: Signature ─────────────────────────────────────────────────

  pw.Widget _signatureBlock(VisitRecord visit, DoctorProfile d) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.end,
      children: [
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            if (visit.signed) ...[
              pw.Text(
                _sigCursive(d.name),
                style: pw.TextStyle(
                  fontSize: 18,
                  fontStyle: pw.FontStyle.italic,
                  fontWeight: pw.FontWeight.bold,
                  color: _teal,
                ),
              ),
            ] else
              pw.Text(
                'Awaiting Signature',
                style: pw.TextStyle(
                  fontSize: 11,
                  fontStyle: pw.FontStyle.italic,
                  color: _grey,
                ),
              ),
            pw.SizedBox(height: 4),
            pw.Container(width: 160, height: 0.5, color: _grey),
            pw.SizedBox(height: 4),
            pw.Text(
              d.name,
              style: pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: _ink,
              ),
            ),
            pw.Text(
              _ddmmyyyy(visit.signedAt ?? visit.createdAt),
              style: pw.TextStyle(fontSize: 9, color: _grey),
            ),
          ],
        ),
      ],
    );
  }

  // ── Helpers ───────────────────────────────────────────────────────────────

  /// Small label + bold value column used in the patient row.
  pw.Widget _lv(String label, String value) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(label, style: pw.TextStyle(fontSize: 8, color: _grey)),
        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 10,
            fontWeight: pw.FontWeight.bold,
            color: _ink,
          ),
        ),
      ],
    );
  }

  String _ddmmyyyy(DateTime dt) =>
      '${dt.day.toString().padLeft(2, '0')}/${dt.month.toString().padLeft(2, '0')}/${dt.year}';

  String _genderLabel(Sex? sex) {
    switch (sex) {
      case Sex.male:
        return 'Male';
      case Sex.female:
        return 'Female';
      case Sex.other:
        return 'Other';
      case null:
        return '—';
    }
  }

  String _phoneLabel(PatientProfile? p) {
    final num = p?.whatsappNumber ?? p?.phone;
    return (num == null || num.isEmpty) ? '—' : '+91 $num';
  }

  /// Produces an abbreviated cursive-style name for the signature area,
  /// e.g. "Dr. Rajesh Sharma" → "Dr. R. Sharma".
  String _sigCursive(String fullName) {
    final cleaned = fullName.replaceFirst(RegExp(r'^Dr\.?\s*'), '').trim();
    if (cleaned.isEmpty) return fullName;
    final parts = cleaned.split(RegExp(r'\s+'));
    if (parts.length == 1) return 'Dr. ${parts.first}';
    final initial = parts.first.isNotEmpty ? parts.first[0] : '';
    return 'Dr. $initial. ${parts.last}';
  }
}

final prescriptionPdfServiceProvider = Provider<PrescriptionPdfService>((ref) {
  return PrescriptionPdfService();
});
