        ['12345', 'xxxxx', 'yyyyy'], 'null'),
  ];

  // ── Report infrastructure ──
  final results = <_Result>[];

  test('Run 450-case mega vernacular stress test', () {
    final sb = StringBuffer();
    sb.writeln();
    sb.writeln('═' * 92);
    sb.writeln('  RXVARTA MEGA VERNACULAR STRESS TEST — 450 CASES');
    sb.writeln('═' * 92);

    for (final c in cases) {
      final icd = mapper.lookup(c.diagnosis);
      final diffs = c.symptoms.isNotEmpty
          ? engine.suggest(c.symptoms)
          : <DifferentialMatch>[];

      final icdOk = _checkIcd(c.expected, icd);
      final diffCount = diffs.length;
      final redFlags = diffs.where((d) => d.isRedFlag).length;

      results.add(_Result(
        caseNum: c.num,
        label: c.label,
        icdCode: icd.code,
        icdConf: icd.confidence,
        diffCount: diffCount,
        redFlags: redFlags,
        icdOk: icdOk,
        expected: c.expected,
      ));

      sb.writeln();
      sb.writeln('CASE ${c.num}: ${c.label}');
      sb.writeln('─' * 72);
      sb.writeln('  Dx:   "${c.diagnosis}"');
      sb.writeln('  Sx:   ${c.symptoms}');
      sb.writeln('  ICD:  ${icd.code ?? "null"} '
          '(${icd.confidence ?? "—"}) '
          '${icdOk ? "✅" : "❌"} '
          '[exp: ${c.expected}]');
      if (diffs.isNotEmpty) {
        for (final d in diffs) {
          final flag = d.isRedFlag ? ' 🚩' : '';
          sb.writeln('  Diff: ${d.name} (${d.icdCode})$flag');
        }
      } else {
        sb.writeln('  Diff: none');
      }
    }

    // ── Summary ──
    sb.writeln();
    sb.writeln('═' * 92);
    sb.writeln('  SUMMARY BY LANGUAGE');
    sb.writeln('═' * 92);

    final langRanges = {
      'Hindi/Hinglish': (1, 60),
      'Telugu': (61, 120),
      'Tamil': (121, 170),
      'Kannada': (171, 220),
      'Bengali': (221, 270),
      'Odia': (271, 310),
      'Gujarati': (311, 350),
      'Marathi': (351, 390),
      'Pediatric': (391, 410),
      'Elderly': (411, 425),
      'STT Artifacts': (426, 440),
      'Adversarial': (441, 450),
    };

    var totalMatched = 0, totalExpNull = 0, totalUnexpNull = 0, totalFail = 0;

    sb.writeln('  ${'Language'.padRight(18)}${'Cases'.padRight(8)}'
        '${'Match'.padRight(8)}${'Null(ok)'.padRight(10)}'
        '${'Null(!)'.padRight(10)}${'Fail'.padRight(8)}');
    sb.writeln('  ${'─' * 60}');

    for (final entry in langRanges.entries) {
      final lang = entry.key;
      final lo = entry.value.$1;
      final hi = entry.value.$2;
      final subset = results.where((r) => r.caseNum >= lo && r.caseNum <= hi);
      var m = 0, en = 0, un = 0, f = 0;
      for (final r in subset) {
        if (!r.icdOk) {
          f++;
        } else if (r.icdCode != null) {
          m++;
        } else if (r.expected == 'null') {
          en++;
        } else {
          un++;
        }
      }
      totalMatched += m;
      totalExpNull += en;
      totalUnexpNull += un;
      totalFail += f;
      sb.writeln('  ${lang.padRight(18)}${subset.length.toString().padRight(8)}'
          '${m.toString().padRight(8)}${en.toString().padRight(10)}'
          '${un.toString().padRight(10)}${f.toString().padRight(8)}');
    }
    sb.writeln('  ${'─' * 60}');
    sb.writeln('  ${'TOTAL'.padRight(18)}${results.length.toString().padRight(8)}'
        '${totalMatched.toString().padRight(8)}${totalExpNull.toString().padRight(10)}'
        '${totalUnexpNull.toString().padRight(10)}${totalFail.toString().padRight(8)}');
    sb.writeln();
    sb.writeln('  VERDICT: $totalMatched matched | '
        '$totalExpNull null (expected) | '
        '$totalUnexpNull null (unexpected) | '
        '$totalFail expectation failures');
    sb.writeln('═' * 92);

    // ignore: avoid_print
    print(sb.toString());

    expect(totalUnexpNull, 0,
        reason: 'Cases expected a match but got null — add synonyms');
    expect(totalFail, 0,
        reason: 'ICD expectation failures');
  });
}

class _Case {
  final int num;
  final String label;
  final String diagnosis;
  final List<String> symptoms;
  final String expected;
  const _Case(this.num, this.label, this.diagnosis, this.symptoms, this.expected);
}

class _Result {
  final int caseNum;
  final String label;
  final String? icdCode;
  final String? icdConf;
  final int diffCount;
  final int redFlags;
  final bool icdOk;
  final String expected;
  const _Result({
    required this.caseNum,
    required this.label,
    required this.icdCode,
    required this.icdConf,
    required this.diffCount,
    required this.redFlags,
    required this.icdOk,
    required this.expected,
  });
}

bool _checkIcd(String expected, IcdMatch icd) {
  switch (expected) {
    case 'match':
      return icd.hasMatch;
    case 'null':
      return !icd.hasMatch;
    case 'any':
      return true;
    default:
      return false;
  }
}
